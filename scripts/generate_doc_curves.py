"""Generate the documented ripple-removal curve from real solves.

Honesty requirement: the curve printed in ``docs/guide.md`` must be produced by
the actual fairing kernel, not typed in by hand. This script runs the fairing
on shaken planes covering several control-grid resolutions and ripple wave
numbers (normal mode, locked boundary, attachment 0.3), measures the spectral
high-frequency removal ratio and the direct energy change, and writes the rows
to ``docs/curves.json``. ``scripts/validate_contract.py`` then re-solves two
anchors and checks they still match this file.

Run::

    PYTHONPATH=. .venv/bin/python scripts/generate_doc_curves.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np

from surface_fairing.core.bspline import BSplineSurface, greville_abscissae
from surface_fairing.core.constraints import HardConstraints
from surface_fairing.core.energy import direct_energy
from surface_fairing.core.fairing import fair_surface

EDGES = ("u0", "u1", "v0", "v1")


def _hf_rms(surf, grid=48, cutoff=3):
    ts = np.linspace(0.0, 1.0, grid)
    Z = np.array([[surf.evaluate(u, v)[2] for v in ts] for u in ts])
    F = np.fft.fft2(Z - Z.mean())
    k = np.minimum(np.arange(grid), grid - np.arange(grid))
    KU, KV = np.meshgrid(k, k, indexing="ij")
    mask = (np.abs(KU) >= cutoff) | (np.abs(KV) >= cutoff)
    return float(np.sqrt(np.mean(np.real(np.fft.ifft2(F * mask)) ** 2)))


def _max_edge_displacement(a, b, n=64):
    return max(
        float(np.linalg.norm(a.edge_samples(e, n) - b.edge_samples(e, n),
                             axis=1).max()) for e in EDGES)


def _plane(n, waves, amplitude=0.04):
    g = greville_abscissae(n, 3)
    U, V = np.meshgrid(g, g, indexing="ij")
    ripple = amplitude * np.sin(2 * np.pi * waves * U) * np.sin(
        2 * np.pi * waves * V)
    ripple[0, :] = ripple[-1, :] = ripple[:, 0] = ripple[:, -1] = 0.0
    return BSplineSurface(np.stack([U, V, ripple], axis=-1),
                          name=f"plane_n{n}_w{waves}")


def _locked(surf):
    hard = HardConstraints(3 * surf.n_control)
    for edge in EDGES:
        hard.pin_edge(surf, edge)
    return hard


def main() -> int:
    rows = []
    # grid sizes that resolve low to near-Nyquist ripple; 21^2 is included so
    # the curve shows that refinement alone does not replace enough data.
    for n in (9, 13, 17, 21):
        for waves in (1, 2, 3):
            s = _plane(n, waves)
            res = fair_surface(s, _locked(s), bend_mode="normal",
                               attachment_weight=0.3)
            hf0, hf1 = _hf_rms(s), _hf_rms(res.faired)
            rows.append({
                "grid": n, "waves": waves,
                "hf_rms_before": hf0,
                "hf_rms_after": hf1,
                "hf_removal_ratio": float(1 - hf1 / hf0) if hf0 > 0 else 0.0,
                "energy_before": res.direct_before,
                "energy_after": res.direct_after,
                "energy_reduction_ratio": res.energy_reduction_ratio,
                "max_edge_displacement": _max_edge_displacement(s, res.faired),
                "hard_constraint_error": res.hard_constraint_error,
            })
            print(f"grid {n:2d} waves {waves}: HF removed "
                  f"{rows[-1]['hf_removal_ratio']:.1%}, energy "
                  f"{rows[-1]['energy_reduction_ratio']:.1%}, "
                  f"boundary {rows[-1]['max_edge_displacement']:.1e}")

    out = Path(__file__).resolve().parent.parent / "docs" / "curves.json"
    out.write_text(json.dumps({
        "description": "plane normal-mode ripple removal vs grid resolution, "
                       "generated by scripts/generate_doc_curves.py",
        "settings": {"bend_mode": "normal", "attachment_weight": 0.3,
                     "amplitude": 0.04, "locked_edges": list(EDGES)},
        "plane_curve": rows,
    }, indent=2))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
